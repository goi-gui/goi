//go:build !js && !wasip1

package main

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const assetsSource = `// Code generated by goi build. DO NOT EDIT.

package goiassets

import "embed"

//go:embed all:*
var FS embed.FS
`

// prepareEmbed writes one small Go file inside the assets directory and one in
// the entrypoint package. The first declares the go:embed for the whole assets
// tree; the second registers it with ui in an init function. Nothing is copied:
// the build reads the files where they already live and removes the two files
// when it is done.
func prepareEmbed(moduleDir, entrypoint, assetsDir string) (func(), error) {
	assetsAbs := resolvePath(moduleDir, assetsDir)
	if sameDir(assetsAbs, moduleDir) {
		return nil, errors.New("goi build needs the assets directory below the project root")
	}
	rel, err := filepath.Rel(moduleDir, assetsAbs)
	if err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return nil, fmt.Errorf("assets directory %s is outside the project", assetsDir)
	}
	module, err := modulePath(moduleDir)
	if err != nil {
		return nil, err
	}
	if _, err := os.Stat(assetsAbs); err != nil {
		return nil, fmt.Errorf("assets directory %s: %w", assetsDir, err)
	}

	assetsFile := filepath.Join(assetsAbs, "goi_embed_gen.go")
	cmdFile := filepath.Join(resolvePath(moduleDir, entrypoint), "goi_embed_gen.go")
	for _, file := range []string{assetsFile, cmdFile} {
		if _, err := os.Stat(file); err == nil {
			return nil, fmt.Errorf("%s already exists", file)
		} else if !errors.Is(err, os.ErrNotExist) {
			return nil, err
		}
	}

	cmdSource := fmt.Sprintf(`// Code generated by goi build. DO NOT EDIT.

package main

import (
	"github.com/goi-gui/goi/ui"
	goiassets %q
)

func init() { ui.RegisterAssets(goiassets.FS) }
`, module+"/"+filepath.ToSlash(rel))

	cleanup := func() {
		os.Remove(assetsFile)
		os.Remove(cmdFile)
	}
	if err := os.WriteFile(assetsFile, []byte(assetsSource), 0o644); err != nil {
		return nil, err
	}
	if err := os.WriteFile(cmdFile, []byte(cmdSource), 0o644); err != nil {
		cleanup()
		return nil, err
	}
	return cleanup, nil
}

func resolvePath(base, path string) string {
	if filepath.IsAbs(path) {
		return path
	}
	return filepath.Join(base, path)
}

func sameDir(a, b string) bool {
	aa, err := filepath.Abs(a)
	if err != nil {
		return false
	}
	bb, err := filepath.Abs(b)
	if err != nil {
		return false
	}
	return filepath.Clean(aa) == filepath.Clean(bb)
}

// modulePath is the module line of go.mod, without quotes.
func modulePath(dir string) (string, error) {
	b, err := os.ReadFile(filepath.Join(dir, "go.mod"))
	if err != nil {
		return "", err
	}
	for _, line := range strings.Split(string(b), "\n") {
		fields := strings.Fields(line)
		if len(fields) >= 2 && fields[0] == "module" {
			return strings.Trim(fields[1], `"`), nil
		}
	}
	return "", errors.New("go.mod has no module line")
}
